import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { mixExample } from '../content/development-store-metrics.mjs';
import { guides } from '../content/index.mjs';
import { relatedGuides } from '../content/related-guides.mjs';
const root = resolve(new URL('..', import.meta.url).pathname);
const read = path => readFileSync(resolve(root, path), 'utf8');
const slug = 'app-store-conversion-rate-vs-google-play-ctr';
const guide = guides.find(g => g.slug === slug);
assert.equal(guide.published, '2026-11-10');
assert.equal(guide.topic, 'development');
assert.equal(guide.modified, undefined);
assert.equal(guide.appPreview, undefined);
assert.equal(relatedGuides(guide, guides).length, 3);
// Independent integer arithmetic: ratios use hundredths of a percent.
for (const [period, expectedVisitors, expectedClicks, expectedBasisPoints] of [['A', 2000, 120, 600], ['B', 2000, 80, 400]]) {
  const rows = mixExample.filter(row => row.period === period);
  assert.equal(rows.length, 2);
  const visitors = rows.reduce((n, r) => n + r.visitors, 0);
  const clicks = rows.reduce((n, r) => n + r.clicks, 0);
  assert.equal(visitors, expectedVisitors);
  assert.equal(clicks, expectedClicks);
  assert.equal(clicks * 10000, visitors * expectedBasisPoints);
  for (const row of rows) assert.equal(row.clicks * 100, row.visitors * (row.source === 'Search segment' ? 10 : 2));
}
assert.equal(80 + 20, 100);
assert.equal(100 * 100 / 10000, 1);
assert.equal(100 * 100 / 800, 12.5);
assert.equal(120 * 100 / 1000, 12);
assert.equal(6 - 4, 2);
assert.equal(Math.round((6 - 4) / 6 * 1000) / 10, 33.3);
const html = read(`guides/${slug}/index.html`);
for (const text of ['100 ÷ 10,000 × 100 = 1%', '120 ÷ 1,000 × 100 = 12%', '120 ÷ 2,000 = 6%', '80 ÷ 2,000 = 4%', 'not a compulsory four-step funnel', 'invented numbers', 'no pre-orders']) assert(html.includes(text), text);
assert(!html.includes('class="app-install"') && !html.includes('class="install-link'));
assert(html.includes('href="/hire-flutter-developer/"'));
assert(html.includes('href="/savings-goal-tracker/"'));
assert(html.includes('class="review-flow"'));
assert(html.includes('AI-generated editorial illustration'));
assert.equal((html.match(/<table>/g) || []).length, 3);
assert(html.includes('<link rel="canonical" href="https://moocsoft.net/guides/' + slug + '/">'));
const graph = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
const article = graph.find(n => n['@type'] === 'Article');
assert.equal(article.datePublished, '2026-11-10');
assert.equal(article.dateModified, '2026-11-10');
assert.equal(article.headline, guide.title);
for (const path of ['guides/development/index.html', 'guides/index.html', 'guides/app-store-submission-checklist/index.html']) assert(read(path).includes(`/guides/${slug}/`));
assert(read('sitemap.xml').includes(`<loc>https://moocsoft.net/guides/${slug}/</loc>`));
console.log('PASS: independent rate/count checks, traffic mix, honest metric boundaries, native visual, sources, service CTA and crawlable reading paths.');
