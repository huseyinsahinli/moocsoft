import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import largeTextGuides, { largeTextCases } from '../content/development-large-text.mjs';
import { guides } from '../content/index.mjs';
import { sources, site } from '../content/apps.mjs';
import { createRelatedGuideSelector } from '../content/related-guides.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const [guide] = largeTextGuides;
assert.equal(largeTextGuides.length, 1);
assert.equal(guide.topic, 'development');
assert.equal(guide.published, '2026-10-22');
assert.equal(guide.modified, undefined);
assert.equal(guides.filter(item => item.published === guide.published).length, 1);
assert.equal(guides.filter(item => item.slug === guide.slug).length, 1);
assert.equal(largeTextCases.length, 6);
const html = read(`guides/${guide.slug}/index.html`);
assert(html.includes(`<title>${guide.title} | Moocsoft</title>`));
assert(html.includes(`<link rel="canonical" href="${site}/guides/${guide.slug}/">`));
const graph = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
const article = graph.find(item => item['@type'] === 'Article');
assert.equal(article.datePublished, guide.published);
assert.equal(article.dateModified, guide.published);
assert.equal(article.headline, guide.title);
assert.equal(article.articleSection, 'Mobile app development');
assert.equal(article.inLanguage, 'en');
assert(!html.includes('class="app-install"') && !html.includes('class="install-link'));
assert(!html.includes('SoftwareApplication') && !html.includes('app-argument'));
assert(html.includes('aria-label="Discuss a Flutter project"'));
const matrix = guide.sections[2][1];
assert.equal((matrix.match(/<td>Untested<\/td>/g) || []).length, 6);
for (const row of largeTextCases) for (const cell of row) assert(matrix.includes(cell));
for (const text of ['Actual:</strong> Untested', 'Evidence:</strong> None collected', 'not an accessibility certification', 'not an app screen', 'No Moocsoft app has been tested', 'Do not uninstall a production app']) assert(html.includes(text), text);
assert.equal((html.match(/<li><span>0[1-4]<\/span>/g) || []).length, 4);
for (const key of guide.sources) assert(html.includes(sources[key][1].replaceAll('&', '&amp;')));
const selectRelated = createRelatedGuideSelector(guides);
assert.deepEqual(selectRelated(guide).map(item => item.slug), ['mobile-app-bug-report-template', 'flutter-camera-permission-test-checklist', 'mobile-app-mvp-checklist']);
const incoming = guides.find(item => item.slug === 'mobile-app-bug-report-template');
assert(selectRelated(incoming).some(item => item.slug === guide.slug));
assert.equal(incoming.published, '2026-10-12');
assert.equal(incoming.modified, undefined);
for (const path of ['guides/index.html', 'guides/development/index.html', 'guides/mobile-app-bug-report-template/index.html', 'sitemap.xml']) assert(read(path).includes(`/guides/${guide.slug}/`));
const service = read('hire-flutter-developer/index.html');
assert(service.includes('class="service-process"'));
assert.equal((service.match(/class="process-number"/g) || []).length, 4);
assert(service.includes('not a fixed timeline'));
const math = read('math-riddles/index.html');
assert(math.includes('class="product-puzzle-visual"'));
assert(math.includes('teaching diagram, not an app screenshot'));
assert.equal(3 * 4 - 2, 10);
assert.equal(5 * 3 - 2, 13);
assert.equal(6 * 4 - 2, 22);
assert(math.includes('6 × 4 − 2 = 22'));
assert(math.includes('<details class="product-puzzle-answer">'));
console.log('PASS: one Oct22 service guide, six untested cases, primary sources, native journey, reciprocal links and honest service/product visuals.');
