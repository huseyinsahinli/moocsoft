import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import cameraGuides from '../content/development-camera-permissions.mjs';
import { guides } from '../content/index.mjs';
import { site, sources } from '../content/apps.mjs';
import { createRelatedGuideSelector } from '../content/related-guides.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(resolve(root, file), 'utf8');
const [guide] = cameraGuides;
assert.equal(cameraGuides.length, 1, 'Only one new daily article');
assert.equal(guide.slug, 'flutter-camera-permission-test-checklist');
assert.equal(guide.topic, 'development');
assert.equal(guide.published, '2026-10-14');
assert.equal(guide.modified, undefined);
assert.deepEqual(guide.startAction, ['#step-3', 'Jump to the camera test matrix ↓']);
assert.equal(guides.filter(item => item.slug === guide.slug).length, 1);
assert.equal(guides.filter(item => item.published === '2026-10-14').length, 1);

const html = read(`guides/${guide.slug}/index.html`);
assert(html.includes(`<link rel="canonical" href="${site}/guides/${guide.slug}/">`));
assert(html.includes(`<title>${guide.title} | Moocsoft</title>`));
assert(!html.includes('class="app-install"') && !html.includes('class="install-link'));
assert(!html.includes('SoftwareApplication') && !html.includes('app-argument'));
assert(html.includes('aria-label="Discuss a Flutter project"'));
const graph = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
const article = graph.find(item => item['@type'] === 'Article');
assert.equal(article.headline, guide.title);
assert.equal(article.description, guide.description);
assert.equal(article.articleSection, 'Mobile app development');
assert.equal(article.inLanguage, 'en');
assert.equal(article.url, `${site}/guides/${guide.slug}/`);
assert.equal(article.datePublished, '2026-10-14');
assert.equal(article.dateModified, '2026-10-14');
assert(graph.find(item => item['@type'] === 'BreadcrumbList').itemListElement.some(item => item.item.endsWith('/guides/development/')));
for (const key of ['flutterCameraRecipe', 'flutterCameraPlugin', 'appleCameraAuthorization', 'androidRuntimePermissions', 'nutritionStore']) {
  assert(guide.sources.includes(key));
  assert(html.includes(sources[key][1]));
}
const matrix = guide.sections[2][1];
assert.equal((matrix.match(/<tbody>([\s\S]*?)<\/tbody>/)[1].match(/<tr>/g) || []).length, 7);
assert.equal((matrix.match(/<td>Untested<\/td>/g) || []).length, 7, 'Proposed expectations are not fabricated completed tests');
for (const state of ['Camera access not decided', 'Access previously refused', 'Access enabled in Settings', 'Access revoked in Settings', 'Preview interrupted', 'Temporary Android access']) assert(matrix.includes(state));
assert(html.includes('fictional test specification, not a customer story'));
assert(html.includes('Actual:</strong> Untested'));
assert(html.includes('Evidence:</strong> None collected'));
assert(html.includes('not exhaustive device coverage'));
assert(html.includes('Do not uninstall a production app'));
assert(html.includes('declarations and runtime requests are not interchangeable'));
assert(html.includes('does not establish which plugin NutriLens uses'));
assert(html.includes('href="/nutrilens/"') && html.includes('href="/hire-flutter-developer/"'));
const related = createRelatedGuideSelector(guides)(guide);
assert.deepEqual(related.map(item => item.slug), ['mobile-app-bug-report-template', 'mobile-app-mvp-checklist', 'mobile-app-handover-checklist']);
assert(related.every(item => item.topic === 'development'));
for (const file of ['guides/development/index.html', 'guides/index.html', 'guides/mobile-app-mvp-checklist/index.html']) assert(read(file).includes(`/guides/${guide.slug}/`));
const incoming = guides.find(item => item.slug === 'mobile-app-mvp-checklist');
assert.equal(incoming.published, '2026-10-09');
assert.equal(incoming.modified, undefined, 'Link-only change does not reset an older publication date');
assert(read('sitemap.xml').includes(`<loc>${site}/guides/${guide.slug}/</loc>`));
console.log('PASS: camera checklist dated metadata, seven explicitly untested cases, primary references, service-only CTA and reciprocal discovery.');
